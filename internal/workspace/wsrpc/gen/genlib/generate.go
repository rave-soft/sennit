// Package genlib holds the wsrpc code generator's core logic. It is
// factored out of the `gen` main package (internal/workspace/wsrpc/gen) so
// wsrpc's own freshness test can call it directly: a regular package can't
// import a package named "main", so the generator's actual work has to live
// somewhere else, and `gen`'s main.go is left as a thin wrapper that writes
// Generate's output to disk.
//
// See CLIENT-SERVER.md, PR 0.7, and internal/workspace/wsrpc/classes.go's
// doc comment for the overall design this generates code for.
package genlib

import (
	"fmt"
	gofmt "go/format"
	"go/types"
	"regexp"
	"sort"
	"strings"

	gofumpt "mvdan.cc/gofumpt/format"

	"golang.org/x/tools/go/packages"

	"github.com/rave-soft/sennit/internal/workspace/wsrpc"
)

const (
	workspaceImportPath = "github.com/rave-soft/sennit/internal/workspace"
	wireerrImportPath   = "github.com/rave-soft/sennit/internal/wireerr"

	// TypesFileName, LoopbackFileName and ServiceFileName are the
	// generated files' names, relative to the wsrpc package directory --
	// both `gen`'s main.go and this package's own caller in wsrpc's
	// freshness test use these so the two never name the files
	// differently.
	TypesFileName    = "zz_generated_types.go"
	LoopbackFileName = "zz_generated_loopback.go"
	// ServiceFileName lives in the grpcws subpackage, not wsrpc itself:
	// internal/ui imports wsrpc for MethodClasses and must never link
	// google.golang.org/grpc, which the gRPC transport this file builds
	// necessarily pulls in (see grpcws's own doc comment).
	ServiceFileName = "grpcws/zz_generated_service.go"
)

// generatedHeader marks both files as generated per Go's standard
// detection (a comment matching `^// Code generated .* DO NOT EDIT\.$`),
// which golangci-lint's own generated-file exclusion keys off of.
const generatedHeader = "// Code generated by internal/workspace/wsrpc/gen. DO NOT EDIT.\n\n"

// Generate loads internal/workspace, walks workspace.Workspace's U and C
// methods (per wsrpc.MethodClasses), and returns the gofumpt-formatted
// contents of zz_generated_types.go, zz_generated_loopback.go and
// grpcws/zz_generated_service.go. Both `gen`'s main.go and wsrpc's own
// freshness test call this, so "run the generator" and "check the
// generator's output" can never disagree about what it produces.
//
// zz_generated_types.go and zz_generated_loopback.go still cover every U
// and C method: Loopback round-trips a C getter through the JSON codec
// in-process exactly like a U call (CLIENT-SERVER.md, PR 0.7), and Snapshot
// needs C's Request/Response DTOs nowhere but here doesn't apply -- C's own
// state travels inside workspace.ClientState instead, but the DTOs stay
// harmless, unused-outside-Loopback types. grpcws/zz_generated_service.go
// (the gRPC service and Client's generated methods) covers U only as of PR
// 1.4b: a class-C getter is answered from grpcws.Client's local cache
// (client_manual.go), never by a round trip, so generating an RPC and a
// Client method for it would be a wire path nothing calls.
func Generate() (typesSrc, loopbackSrc, serviceSrc []byte, err error) {
	methods, err := loadMethods()
	if err != nil {
		return nil, nil, nil, err
	}
	typesSrc, err = renderTypes(methods)
	if err != nil {
		return nil, nil, nil, fmt.Errorf("rendering %s: %w", TypesFileName, err)
	}
	loopbackSrc, err = renderLoopback(methods)
	if err != nil {
		return nil, nil, nil, fmt.Errorf("rendering %s: %w", LoopbackFileName, err)
	}
	serviceSrc, err = renderService(onlyClass(methods, wsrpc.U))
	if err != nil {
		return nil, nil, nil, fmt.Errorf("rendering %s: %w", ServiceFileName, err)
	}
	return typesSrc, loopbackSrc, serviceSrc, nil
}

// onlyClass filters methods down to the ones classified class -- used to
// hand renderService the U-only subset while renderTypes/renderLoopback
// still get every U and C method (see Generate's own doc comment).
func onlyClass(methods []*methodInfo, class wsrpc.Class) []*methodInfo {
	var out []*methodInfo
	for _, m := range methods {
		if m.Class == class {
			out = append(out, m)
		}
	}
	return out
}

// paramInfo is one parameter of a Workspace method, in its original
// declared order and position.
type paramInfo struct {
	// LocalName is the identifier used for this parameter in the
	// generated Loopback method's own signature: the interface
	// declaration's own name, or argN when the interface left it
	// unnamed.
	LocalName string
	Type      types.Type
	IsCtx     bool
	// Variadic is set on the last parameter of a variadic method; Type
	// is already the slice type (types.Signature.Params reports it that
	// way), so building the "...Elem" form just needs Type.(*types.Slice).Elem().
	Variadic bool
}

// fieldInfo is one field of a generated Request or Response struct.
type fieldInfo struct {
	GoName   string
	JSONName string
	Type     types.Type
	// ParamLocalName is the source parameter's LocalName, set only on
	// ReqFields (a Response field has no such source; it comes from a
	// call result instead).
	ParamLocalName string
}

// methodInfo is everything the generator needs to know about one U or C
// Workspace method.
type methodInfo struct {
	Name   string
	Class  wsrpc.Class
	Params []paramInfo // full original parameter list, ctx included
	// Results is the full original result list, in order; its last entry
	// is the error type when HasErr.
	Results   []types.Type
	HasErr    bool
	ReqFields []fieldInfo // Params minus context.Context, in order
	ResFields []fieldInfo // Results minus a trailing error, in order
}

// loadMethods loads workspace.Workspace via go/packages and returns a
// methodInfo for every method classified U or C in wsrpc.MethodClasses,
// sorted by name.
func loadMethods() ([]*methodInfo, error) {
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedTypes | packages.NeedTypesInfo |
			packages.NeedSyntax | packages.NeedImports | packages.NeedDeps,
	}
	pkgs, err := packages.Load(cfg, workspaceImportPath)
	if err != nil {
		return nil, fmt.Errorf("loading %s: %w", workspaceImportPath, err)
	}
	if len(pkgs) != 1 {
		return nil, fmt.Errorf("loading %s: expected 1 package, got %d", workspaceImportPath, len(pkgs))
	}
	pkg := pkgs[0]
	if len(pkg.Errors) > 0 {
		return nil, fmt.Errorf("loading %s: %v", workspaceImportPath, pkg.Errors)
	}

	obj := pkg.Types.Scope().Lookup("Workspace")
	if obj == nil {
		return nil, fmt.Errorf("%s has no Workspace declaration", workspaceImportPath)
	}
	iface, ok := obj.Type().Underlying().(*types.Interface)
	if !ok {
		return nil, fmt.Errorf("%s.Workspace is not an interface", workspaceImportPath)
	}
	iface.Complete()

	var methods []*methodInfo
	for i := range iface.NumMethods() {
		fn := iface.Method(i)
		class, ok := wsrpc.MethodClasses[fn.Name()]
		if !ok || (class != wsrpc.U && class != wsrpc.C) {
			continue
		}
		mi, err := buildMethodInfo(fn, class)
		if err != nil {
			return nil, fmt.Errorf("method %s: %w", fn.Name(), err)
		}
		methods = append(methods, mi)
	}
	sort.Slice(methods, func(i, j int) bool { return methods[i].Name < methods[j].Name })
	return methods, nil
}

func buildMethodInfo(fn *types.Func, class wsrpc.Class) (*methodInfo, error) {
	sig, ok := fn.Type().(*types.Signature)
	if !ok {
		return nil, fmt.Errorf("method value is not a function signature")
	}
	mi := &methodInfo{Name: fn.Name(), Class: class}

	params := sig.Params()
	n := params.Len()
	for i := range n {
		p := params.At(i)
		isCtx := isContextType(p.Type())
		variadic := sig.Variadic() && i == n-1
		localName := p.Name()
		if localName == "" {
			localName = fmt.Sprintf("arg%d", i)
		}
		mi.Params = append(mi.Params, paramInfo{LocalName: localName, Type: p.Type(), IsCtx: isCtx, Variadic: variadic})
		if isCtx {
			continue
		}
		mi.ReqFields = append(mi.ReqFields, fieldInfo{
			GoName:         exportName(localName),
			JSONName:       toSnakeCase(localName),
			Type:           p.Type(),
			ParamLocalName: localName,
		})
	}

	results := sig.Results()
	rn := results.Len()
	mi.HasErr = rn > 0 && isErrorType(results.At(rn-1).Type())
	dataCount := rn
	if mi.HasErr {
		dataCount = rn - 1
	}
	for i := range rn {
		mi.Results = append(mi.Results, results.At(i).Type())
	}
	for i := range dataCount {
		r := results.At(i)
		var goName, jsonName string
		switch {
		case r.Name() != "":
			goName, jsonName = exportName(r.Name()), toSnakeCase(r.Name())
		case dataCount == 1:
			goName, jsonName = "Result", "result"
		default:
			goName, jsonName = fmt.Sprintf("Result%d", i), fmt.Sprintf("result_%d", i)
		}
		mi.ResFields = append(mi.ResFields, fieldInfo{GoName: goName, JSONName: jsonName, Type: r.Type()})
	}
	return mi, nil
}

func isContextType(t types.Type) bool {
	named, ok := t.(*types.Named)
	if !ok {
		return false
	}
	o := named.Obj()
	return o != nil && o.Pkg() != nil && o.Pkg().Path() == "context" && o.Name() == "Context"
}

var errorType = types.Universe.Lookup("error").Type()

func isErrorType(t types.Type) bool {
	return types.Identical(t, errorType)
}

// exportName capitalizes name's first rune, turning an interface
// parameter's (or named result's) lower-camel-case Go name into an
// exported struct field name -- "sessionID" -> "SessionID".
func exportName(name string) string {
	if name == "" {
		return name
	}
	return strings.ToUpper(name[:1]) + name[1:]
}

// snakeBoundary1 finds a lower/digit-to-upper transition ("sessionID" ->
// the "n"/"I" boundary); snakeBoundary2 finds an upper-run-to-upper+lower
// transition ("MCPName" -> the "P"/"Na" boundary, so an acronym doesn't
// swallow the word that follows it). toSnakeCase applies both, in that
// order, then lowercases the result.
var (
	snakeBoundary2 = regexp.MustCompile(`([A-Z]+)([A-Z][a-z])`)
	snakeBoundary1 = regexp.MustCompile(`([a-z0-9])([A-Z])`)
)

func toSnakeCase(name string) string {
	s := snakeBoundary2.ReplaceAllString(name, "${1}_${2}")
	s = snakeBoundary1.ReplaceAllString(s, "${1}_${2}")
	return strings.ToLower(s)
}

// importSet accumulates the packages a rendered file references, assigning
// each an alias -- its own declared package name, unless that collides
// with a different import path already using it, in which case
// disambiguate picks a longer one. importBlock renders the sorted `import
// (...)` block for whatever ended up registered.
type importSet struct {
	aliasByPath   map[string]string
	pkgNameByPath map[string]string
	pathByAlias   map[string]string
}

func newImportSet() *importSet {
	return &importSet{
		aliasByPath:   map[string]string{},
		pkgNameByPath: map[string]string{},
		pathByAlias:   map[string]string{},
	}
}

// register records path (whose real package name is name) and returns the
// alias to use for it, reusing a previous registration of the same path.
func (s *importSet) register(path, name string) string {
	if alias, ok := s.aliasByPath[path]; ok {
		return alias
	}
	alias := name
	if _, taken := s.pathByAlias[alias]; taken {
		base := disambiguate(path)
		alias = base
		for i := 2; ; i++ {
			if _, taken := s.pathByAlias[alias]; !taken {
				break
			}
			alias = fmt.Sprintf("%s%d", base, i)
		}
	}
	s.aliasByPath[path] = alias
	s.pkgNameByPath[path] = name
	s.pathByAlias[alias] = path
	return alias
}

// qualifier is a types.Qualifier: passed to types.TypeString so every named
// type it stringifies is both correctly qualified and registered for
// importBlock.
func (s *importSet) qualifier(pkg *types.Package) string {
	if pkg == nil {
		return ""
	}
	return s.register(pkg.Path(), pkg.Name())
}

// disambiguate turns an import path into a fallback alias for when its
// package name collides with a different path already using it -- e.g.
// "internal/providers/config" alongside "internal/config", both named
// "config" -> "providersconfig".
func disambiguate(path string) string {
	trimmed := strings.TrimPrefix(path, "github.com/rave-soft/sennit/")
	parts := strings.Split(trimmed, "/")
	if len(parts) >= 2 {
		return parts[len(parts)-2] + parts[len(parts)-1]
	}
	return parts[len(parts)-1]
}

func (s *importSet) importBlock() string {
	if len(s.aliasByPath) == 0 {
		return ""
	}
	paths := make([]string, 0, len(s.aliasByPath))
	for p := range s.aliasByPath {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	var b strings.Builder
	b.WriteString("import (\n")
	for _, p := range paths {
		alias := s.aliasByPath[p]
		if alias == s.pkgNameByPath[p] {
			fmt.Fprintf(&b, "\t%q\n", p)
		} else {
			fmt.Fprintf(&b, "\t%s %q\n", alias, p)
		}
	}
	b.WriteString(")\n")
	return b.String()
}

func typeString(t types.Type, imp *importSet) string {
	return types.TypeString(t, imp.qualifier)
}

// renderTypes builds zz_generated_types.go: a Request and a Response
// struct per method in methods.
func renderTypes(methods []*methodInfo) ([]byte, error) {
	imp := newImportSet()
	var body strings.Builder

	for _, m := range methods {
		fmt.Fprintf(&body, "// %sRequest is the request DTO for workspace.Workspace.%s.\n", m.Name, m.Name)
		fmt.Fprintf(&body, "type %sRequest struct {\n", m.Name)
		for _, f := range m.ReqFields {
			fmt.Fprintf(&body, "\t%s %s `json:%q`\n", f.GoName, typeString(f.Type, imp), f.JSONName)
		}
		body.WriteString("}\n\n")

		fmt.Fprintf(&body, "// %sResponse is the response DTO for workspace.Workspace.%s.\n", m.Name, m.Name)
		fmt.Fprintf(&body, "type %sResponse struct {\n", m.Name)
		for _, f := range m.ResFields {
			fmt.Fprintf(&body, "\t%s %s `json:%q`\n", f.GoName, typeString(f.Type, imp), f.JSONName)
		}
		if m.HasErr {
			wireerrAlias := imp.register(wireerrImportPath, "wireerr")
			fmt.Fprintf(&body, "\tErr *%s.Error `json:\"err,omitempty\"`\n", wireerrAlias)
		}
		body.WriteString("}\n\n")
	}

	src := generatedHeader + "package wsrpc\n\n" + imp.importBlock() + "\n" + body.String()
	return gofumptFormat([]byte(src))
}

// renderLoopback builds zz_generated_loopback.go: the Loopback type and one
// method per entry in methods, each pushing its call through the JSON
// codec before/after delegating to the wrapped workspace.Workspace.
func renderLoopback(methods []*methodInfo) ([]byte, error) {
	imp := newImportSet()
	imp.register("context", "context")
	imp.register("encoding/json", "json")
	imp.register("fmt", "fmt")
	wsAlias := imp.register(workspaceImportPath, "workspace")

	var body strings.Builder
	body.WriteString("// Loopback wraps a workspace.Workspace and pushes every U/C call's\n")
	body.WriteString("// arguments and results through encoding/json before/after delegating to\n")
	body.WriteString("// it -- see this package's doc comment (classes.go) and CLIENT-SERVER.md,\n")
	body.WriteString("// PR 0.7. loopback_manual.go adds the S/H/X methods this file doesn't\n")
	body.WriteString("// cover, so *Loopback satisfies workspace.Workspace in full.\n")
	fmt.Fprintf(&body, "type Loopback struct {\n\tinner %s.Workspace\n}\n\n", wsAlias)
	body.WriteString("// NewLoopback wraps inner so every U/C call round-trips through the JSON\n")
	body.WriteString("// codec before reaching it.\n")
	fmt.Fprintf(&body, "func NewLoopback(inner %s.Workspace) *Loopback {\n\treturn &Loopback{inner: inner}\n}\n\n", wsAlias)

	for _, m := range methods {
		writeLoopbackMethod(&body, imp, m, wsAlias)
		body.WriteString("\n")
	}

	src := generatedHeader + "package wsrpc\n\n" + imp.importBlock() + "\n" + body.String()
	return gofumptFormat([]byte(src))
}

// Every local variable this function introduces is prefixed "wsrpc" so it
// can never collide with a real Workspace parameter name -- CreateThread's
// own "req proto.CreateThreadRequest" parameter is exactly such a
// collision waiting to happen with an unprefixed "req".
const (
	varReq           = "wsrpcReq"
	varReqJSON       = "wsrpcReqJSON"
	varDecodedReq    = "wsrpcDecodedReq"
	varResp          = "wsrpcResp"
	varRespJSON      = "wsrpcRespJSON"
	varDecodedResp   = "wsrpcDecodedResp"
	varErrMarshal1   = "wsrpcErr1"
	varErrUnmarshal1 = "wsrpcErr2"
	varErrMarshal2   = "wsrpcErr3"
	varErrUnmarshal2 = "wsrpcErr4"
	varResultPrefix  = "wsrpcOut"
	varCallCtx       = "wsrpcCallCtx"
	varCallCancel    = "wsrpcCallCancel"
)

// hasCtxParam reports whether m takes a context.Context parameter -- every
// U/C method that does gets a call-scoped ctx (see writeLoopbackMethod)
// rather than the caller's own, so a wire hop's real ctx lifetime (a unary
// gRPC handler's ctx is cancelled the instant it returns) reproduces
// in-process under SENNIT_TEST_WIRE=1 too.
func hasCtxParam(m *methodInfo) bool {
	for _, p := range m.Params {
		if p.IsCtx {
			return true
		}
	}
	return false
}

func writeLoopbackMethod(body *strings.Builder, imp *importSet, m *methodInfo, wsAlias string) {
	paramSig := buildParamSig(m, imp)
	resultSig := buildResultSig(m, imp)
	fmt.Fprintf(body, "func (l *Loopback) %s(%s) (%s) {\n", m.Name, paramSig, resultSig)

	fmt.Fprintf(body, "\t%s := %sRequest{\n", varReq, m.Name)
	for _, f := range m.ReqFields {
		fmt.Fprintf(body, "\t\t%s: %s,\n", f.GoName, f.ParamLocalName)
	}
	body.WriteString("\t}\n")

	codecStep(body, m, varReqJSON, varErrMarshal1, fmt.Sprintf("json.Marshal(%s)", varReq), "marshaling", m.Name, "request")
	fmt.Fprintf(body, "\tvar %s %sRequest\n", varDecodedReq, m.Name)
	codecStep(body, m, "", varErrUnmarshal1, fmt.Sprintf("json.Unmarshal(%s, &%s)", varReqJSON, varDecodedReq), "decoding", m.Name, "request")

	// callCtx is cancelled the instant l.inner's call returns, mirroring a
	// real unary gRPC handler's own ctx lifetime (grpc-go cancels it right
	// after the handler returns, success or not). Anything the inner
	// implementation starts on this ctx and expects to outlive the call --
	// a goroutine, a subprocess, a subscription -- dies here too, the same
	// way it would over the wire, instead of surviving only because
	// Loopback happened to hand it the long-lived caller ctx unchanged.
	hasCtx := hasCtxParam(m)
	if hasCtx {
		fmt.Fprintf(body, "\t%s, %s := context.WithCancel(ctx)\n", varCallCtx, varCallCancel)
	}
	callArgs := buildCallArgs(m, hasCtx)
	innerResVars := make([]string, len(m.Results))
	for i := range m.Results {
		innerResVars[i] = fmt.Sprintf("%s%d", varResultPrefix, i)
	}
	fmt.Fprintf(body, "\t%s := l.inner.%s(%s)\n", strings.Join(innerResVars, ", "), m.Name, callArgs)
	if hasCtx {
		fmt.Fprintf(body, "\t%s()\n", varCallCancel)
	}

	fmt.Fprintf(body, "\t%s := %sResponse{\n", varResp, m.Name)
	for i, f := range m.ResFields {
		fmt.Fprintf(body, "\t\t%s: %s,\n", f.GoName, innerResVars[i])
	}
	if m.HasErr {
		fmt.Fprintf(body, "\t\tErr: %s.EncodeError(%s),\n", wsAlias, innerResVars[len(innerResVars)-1])
	}
	body.WriteString("\t}\n")

	codecStep(body, m, varRespJSON, varErrMarshal2, fmt.Sprintf("json.Marshal(%s)", varResp), "marshaling", m.Name, "response")
	fmt.Fprintf(body, "\tvar %s %sResponse\n", varDecodedResp, m.Name)
	codecStep(body, m, "", varErrUnmarshal2, fmt.Sprintf("json.Unmarshal(%s, &%s)", varRespJSON, varDecodedResp), "decoding", m.Name, "response")

	for i, f := range m.ResFields {
		fmt.Fprintf(body, "\tres%d = %s.%s\n", i, varDecodedResp, f.GoName)
	}
	if m.HasErr {
		fmt.Fprintf(body, "\terr = %s.DecodeError(%s.Err)\n", wsAlias, varDecodedResp)
	}
	body.WriteString("\treturn\n}\n")
}

// codecStep emits one marshal/unmarshal call and its failure handling.
// valueVar is the value variable to declare alongside errVar ("reqJSON"),
// or "" for a call that returns only an error (json.Unmarshal); expr is the
// call itself; verb/method/kind build the wrapped message ("marshaling
// FooRequest request"). A method with an error result reports the codec
// failure as its own error; one without panics, since it has no result to
// report it through and a codec failure here is a bug in the generated
// pair of types, not a runtime condition a caller could recover from.
func codecStep(body *strings.Builder, m *methodInfo, valueVar, errVar, expr, verb, method, kind string) {
	if valueVar != "" {
		fmt.Fprintf(body, "\t%s, %s := %s\n", valueVar, errVar, expr)
	} else {
		fmt.Fprintf(body, "\t%s := %s\n", errVar, expr)
	}
	msg := fmt.Sprintf("%s %s %s", verb, method, kind)
	if m.HasErr {
		fmt.Fprintf(body, "\tif %s != nil {\n\t\terr = fmt.Errorf(\"wsrpc: %s: %%w\", %s)\n\t\treturn\n\t}\n", errVar, msg, errVar)
	} else {
		fmt.Fprintf(body, "\tif %s != nil {\n\t\tpanic(fmt.Sprintf(\"wsrpc: %s: %%v\", %s))\n\t}\n", errVar, msg, errVar)
	}
}

func buildCallArgs(m *methodInfo, useCallCtx bool) string {
	var parts []string
	for _, p := range m.Params {
		if p.IsCtx {
			if useCallCtx {
				parts = append(parts, varCallCtx)
			} else {
				parts = append(parts, "ctx")
			}
			continue
		}
		arg := varDecodedReq + "." + exportName(p.LocalName)
		if p.Variadic {
			arg += "..."
		}
		parts = append(parts, arg)
	}
	return strings.Join(parts, ", ")
}

func buildParamSig(m *methodInfo, imp *importSet) string {
	var parts []string
	for _, p := range m.Params {
		if p.Variadic {
			sl := p.Type.(*types.Slice)
			parts = append(parts, fmt.Sprintf("%s ...%s", p.LocalName, typeString(sl.Elem(), imp)))
			continue
		}
		parts = append(parts, fmt.Sprintf("%s %s", p.LocalName, typeString(p.Type, imp)))
	}
	return strings.Join(parts, ", ")
}

func buildResultSig(m *methodInfo, imp *importSet) string {
	var parts []string
	for i, t := range m.Results {
		name := fmt.Sprintf("res%d", i)
		if m.HasErr && i == len(m.Results)-1 {
			name = "err"
		}
		parts = append(parts, fmt.Sprintf("%s %s", name, typeString(t, imp)))
	}
	return strings.Join(parts, ", ")
}

// modulePath is this repo's module path, passed to gofumpt as
// Options.ModulePath (it affects import-grouping decisions -- which
// import paths count as "not stdlib").
const modulePath = "github.com/rave-soft/sennit"

// langVersion is the Go language version gofumpt formats against,
// matching go.mod's own `go` directive so the same rules apply here as
// `gofumpt -w .` (task fmt) applies to the rest of the tree. Go's toolchain
// allows a three-component version in go.mod (e.g. "1.27.0"); go/version
// wants "go1.27.0", so this just prepends "go" -- there is no
// `go list -m -f {{.GoVersion}}` call here since that would need a
// subprocess too, which is exactly what this function exists to avoid.
const langVersion = "go1.27.0"

// gofumptFormat gofmt-then-gofumpt-formats src in-process, matching the
// formatting the committed generated files went through (see AGENTS.md's
// Formatting section) so the freshness test's byte comparison actually
// means something. This used to shell out to a `gofumpt` binary on PATH,
// which meant TestGeneratedFilesAreFresh needed that binary at test time
// and would fail on any CI job or contributor machine that only has the Go
// toolchain installed (see .github/workflows/build.yml's `build`/`race`
// jobs) -- and made the generator's output depend on whichever gofumpt
// version happened to be on PATH rather than the one pinned in go.mod.
// mvdan.cc/gofumpt/format is the same formatter gofumpt's CLI wraps, used
// here as a library instead.
func gofumptFormat(src []byte) ([]byte, error) {
	formatted, err := gofmt.Source(src)
	if err != nil {
		return nil, fmt.Errorf("gofmt: %w\n%s", err, src)
	}
	out, err := gofumpt.Source(formatted, gofumpt.Options{
		LangVersion: langVersion,
		ModulePath:  modulePath,
	})
	if err != nil {
		return nil, fmt.Errorf("gofumpt: %w", err)
	}
	return out, nil
}
